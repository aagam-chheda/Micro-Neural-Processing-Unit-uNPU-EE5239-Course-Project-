def build_report(m):
    """render tools/report_src/*.md: every @@id@@ is replaced by the value read from the log (KEYS); an unknown or
    unresolved token is a build error. Results: 16_docs_and_report/<name>.md and a copy in docs/report/."""
    src_dir = os.path.join(m.HERE, 'report_src')
    vals = {k['id']: k['value'] for k in KEYS}
    for name in sorted(os.listdir(src_dir)):
        if not name.endswith('.md'):
            continue
        text = open(os.path.join(src_dir, name), encoding='utf-8').read()
        used = set(re.findall(r'@@(\w+)@@', text))
        unknown = sorted(u for u in used if u not in vals)
        if unknown:
            m.die('report %s uses unknown tokens: %s' % (name, ', '.join(unknown)))
        out = re.sub(r'@@(\w+)@@', lambda mo: vals[mo.group(1)], text)
        if '@@' in out:
            m.die('report %s: a token is left unresolved' % name)
        data = out.encode('utf-8')
        m.emit('16_docs_and_report/' + name, data, 'generated:build_final.py from tools/report_src/' + name + ' (tokens from the logs)')
        m.emit('docs/report/' + name, data, 'generated:build_final.py from tools/report_src/' + name)
        DOCS_ROWS.append(('report/' + name, data))

