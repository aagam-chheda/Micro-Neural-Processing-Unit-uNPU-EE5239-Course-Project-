def purpose(m, path, data):
    txt = data.decode(errors='replace').split('\n')
    if path.endswith('.md'):
        for l in txt:
            if l.startswith('#'):
                return l.lstrip('# ').strip()[:160]
    for l in txt[:60]:
        s = l.strip()
        if not s or s.startswith('#!') or set(s) <= set('#-=/*'):
            continue
        for lead in ('##', '#', '//', '--', '*', '/*'):
            if s.startswith(lead):
                s = s[len(lead):].strip()
                break
        else:
            continue
        if len(s) > 12:
            return s[:160]
    return '(no header comment found)'


