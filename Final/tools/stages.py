def _read(path):
    with open(path, 'rb') as f:
        return f.read().decode(errors='replace')


def runbook_section(m, n):
    txt = m.git_content(RUNBOOK).decode()
    mm = re.search(r'^## %d\. .*?(?=^## |\Z)' % n, txt, re.S | re.M)
    return mm.group(0) if mm else ''


def runbook_commands(m, steps):
    out = []
    for n in steps:
        sec = runbook_section(m, n)
        title = sec.split('\n', 1)[0] if sec else '## %d (section not found)' % n
        blocks = re.findall(r'```[a-z]*\n(.*?)```', sec, re.S)
        out.append('**RUN3_RUNBOOK step %d** — %s' % (n, title.lstrip('# ').strip()))
        if blocks:
            for b in blocks:
                out.append('```\n' + b.rstrip() + '\n```')
        else:
            out.append('(no fenced command block in that section)')
    return '\n\n'.join(out)


def first_line_matching(path, pattern):
    op = open
    if path.endswith('.gz'):
        import gzip
        op = gzip.open
    rx = re.compile(pattern)
    with op(path, 'rt', errors='replace') as f:
        for i, line in enumerate(f, 1):
            if rx.search(line):
                return i, line.rstrip('\n')
    return None, None


def eval_keys(m):
    for k in KEYS:
        p = os.path.join(m.FINAL, k['file'])
        if not os.path.exists(p):
            m.die('key %s: file %s missing' % (k['id'], k['file']))
        rx = re.compile(k['pattern'])
        op = gzip.open if p.endswith('.gz') else open
        hit, found = 0, False
        with op(p, 'rt', errors='replace') as f:
            for i, line in enumerate(f, 1):
                if rx.search(line):
                    hit += 1
                    if hit == k['nth']:
                        mm = re.search(k['valre'], line)
                        if not mm:
                            m.die('key %s: value regex %r does not match line %r' % (k['id'], k['valre'], line))
                        k['value'], k['line'] = mm.group(1), i
                        found = True
                        break
        if not found:
            m.die('key %s: pattern %r (match %d) not found in %s' % (k['id'], k['pattern'], k['nth'], k['file']))


