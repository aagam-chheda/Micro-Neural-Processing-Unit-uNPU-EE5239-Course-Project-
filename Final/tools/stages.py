def doc_info(m, rp, data):
    txt = data.decode(errors='replace')
    title = ''
    mm = re.search(r'<title>(.*?)</title>', txt, re.S | re.I)
    if mm:
        title = re.sub(r'\s+', ' ', mm.group(1)).strip()
    if not title:
        for l in txt.split('\n'):
            if l.startswith('#'):
                title = l.lstrip('# ').strip()
                break
    if not title:
        title = os.path.basename(rp)
    summ = ''
    plain = re.sub(r'<[^>]+>', ' ', txt) if rp.endswith('.html') else txt
    for l in plain.split('\n'):
        s = l.strip()
        if len(s) > 50 and not s.startswith(('#', '|', '```', '-', '*', '=')):
            summ = s[:170]
            break
    d = re.search(r'(20\d\d-\d\d-\d\d)', rp)
    if d:
        date = d.group(1)
    else:
        h = m.git_hist(rp) if rp in m.Ctx.tree else []
        date = m.fmt_t(h[0][1])[:10] if h else (datetime.date.today().isoformat() if rp.startswith('report/') else '(uncommitted)')
    return title[:120], date, summ


